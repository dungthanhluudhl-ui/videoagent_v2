def step_captions(plan, n, m, words_path, check, force):
    fps = plan.get("fps", 30)
    if not words_path.exists():
        print(f"captions: chưa có {words_path} - bỏ qua (chưa tới lúc).")
        return True
    lines = build_caption_lines(words_path, fps)
    data_path = pathlib.Path(f"src/captionData{m}.js")
    shared_path = pathlib.Path(f"src/scenes/shared{m}.jsx")

    if data_path.exists():
        old = data_path.read_text(encoding="utf-8")
        same = parse_caption_js(old) == lines
        if check:
            if not same:
                theirs, ours = parse_caption_js(old), lines
                print(f"captions: {data_path} LỆCH bản sinh từ {words_path} "
                      f"({len(theirs)} dòng trên đĩa / {len(ours)} dòng sinh ra).")
                return False
            print(f"captions: {data_path} khớp bản sinh ({len(lines)} dòng).")
            return True
        if AUTOGEN not in old and not force:
            if same:
                print(f"captions: {data_path} viết tay nhưng khớp nội dung - giữ nguyên.")
                return True
            print(f"captions: {data_path} viết tay và LỆCH bản sinh - giữ nguyên "
                  "(dùng --force nếu thật sự muốn thay).")
            return True
    if check:
        print(f"captions: {data_path} chưa tồn tại - sẽ được sinh ({len(lines)} dòng).")
        return True

    data_path.write_text(caption_js(m, lines), encoding="utf-8")
    print(f"captions: đã ghi {data_path} ({len(lines)} dòng).")
    if not shared_path.exists():
        shared_path.write_text(SHARED_TEMPLATE.format(m=m, autogen=AUTOGEN), encoding="utf-8")
        print(f"captions: đã ghi {shared_path} (Captions{m}).")
    return True


# ------------------------------------------------------------------ master

def master_jsx(plan, n, m, parts):
    audio = plan.get("audioFile", f"audio{m}.mp3")
    # rail k đệm đúng thời lượng transition ĐỨNG SAU nó; rail cuối đệm T làm
    # đuôi thở (khớp mọi master đã ship). "none" ở cảnh k+1 = không transition
    # sau cảnh k = rail k không đệm.
    pads = []
    n_fades = 0
    for i in range(len(parts)):
        if i == len(parts) - 1:
            pads.append(True)
        else:
            fade_after = parts[i + 1][3] == "fade"
            pads.append(fade_after)
            n_fades += fade_after

    imports = "\n".join(f'import {{ {c}, {d} }} from "./scenes/{c}";'
                        for _, c, d, _t in parts)
    dur_terms = " +\n  ".join(f"({d} + T)" if pads[i] else f"{d}"
                              for i, (_, _c, d, _t) in enumerate(parts))
    body = []
    for i, (_, comp, dur, _t) in enumerate(parts):
        if i > 0 and parts[i][3] == "fade":
            body.append("      <TransitionSeries.Transition presentation={fade()} "
                        "timing={linearTiming({ durationInFrames: T })} />")
        rail = f"{dur} + T" if pads[i] else dur
        body.append(f"      <TransitionSeries.Sequence durationInFrames={{{rail}}}>\n"
                    f"        <{comp} />\n"
                    f"      </TransitionSeries.Sequence>")
    return f'''/**
 * V{n}Master - master timeline, {AUTOGEN} từ input/scene_plan{n}.json.
 *
 * Đừng sửa tay - sinh lại bằng:
 *   py -3 .claude/skills/vox-collage-video/scripts/assemble.py input/scene_plan{n}.json
 *
 * Luật rail (SKILL.md bước 7): TransitionSeries rút ngắn timeline đúng bằng
 * mỗi khoảng chồng, nên MỌI rail - kể cả rail ĐẦU - phải đệm đúng thời lượng
 * transition đứng sau nó; đệm thiếu rail đầu là mọi cảnh từ S2 trôi sớm nửa
 * giây so với audio của chính nó (lỗi đã ship một lần ở V10).
 */

import {{ AbsoluteFill, Audio, staticFile }} from "remotion";
import {{ TransitionSeries, linearTiming }} from "@remotion/transitions";
import {{ fade }} from "@remotion/transitions/fade";

{imports}
import {{ Captions{m} }} from "./scenes/shared{m}";

const T = {T_FADE};

export const MASTER{n}_DURATION =
  {dur_terms} - {n_fades} * T;

export const V{n}Master = () => (
  <AbsoluteFill style={{{{ backgroundColor: "{CANVAS_BG}" }}}}>
    <Audio src={{staticFile("{audio}")}} />

    <TransitionSeries>
{chr(10).join(body)}
    </TransitionSeries>

    {{/* Phụ đề mount MỘT LẦN ở master, là anh em ĐỨNG SAU TransitionSeries -
        đặt bên trong thì nó bị cuốn theo từng lần chuyển cảnh. */}}
    <Captions{m} />
  </AbsoluteFill>
);
'''


def step_master(plan, n, m, parts, check, force):
    missing = [c for _, c, _d, _t in parts
               if not pathlib.Path(f"src/scenes/{c}.jsx").exists()]
    if missing:
        print(f"master: còn {len(missing)} cảnh chưa dựng ({', '.join(missing[:5])}"
              f"{'...' if len(missing) > 5 else ''}) - bỏ qua (chưa tới lúc).")
        return True
    shared_path = pathlib.Path(f"src/scenes/shared{m}.jsx")
    if not shared_path.exists():
        print(f"master: thiếu {shared_path} (Captions{m}) - chạy bước captions trước.")
        return False

    content = master_jsx(plan, n, m, parts)
    path = pathlib.Path(f"src/V{n}Master.jsx")
    if check:
        if not path.exists():
            print(f"master: {path} chưa được sinh dù mọi cảnh đã dựng - chạy assemble.")
            return False
        old = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if old != content:
            print(f"master: {path} LỆCH bản sinh từ plan - rail/cảnh đã bị sửa tay "
                  "lệch khỏi hợp đồng. Sinh lại bằng assemble, đừng vá tay.")
            return False
        print(f"master: {path} khớp bản sinh ({len(parts)} cảnh).")
        return True
    if path.exists() and AUTOGEN not in path.read_text(encoding="utf-8") and not force:
        print(f"master: {path} là file viết tay, không đè (dùng --force nếu chắc chắn).")
        return False
    path.write_text(content, encoding="utf-8")
    print(f"master: đã ghi {path} ({len(parts)} cảnh, {n_fades_msg(parts)}).")
    return True


def n_fades_msg(parts):
    n_fades = sum(1 for p in parts[1:] if p[3] == "fade")
    cuts = len(parts) - 1 - n_fades
    return f"{n_fades} fade" + (f", {cuts} cắt thẳng" if cuts else "")


# ---------------------------------------------------------------- register

INDEX_TS = '''import { registerRoot } from "remotion";
import { PrevisRoot } from "./PrevisRoot";

registerRoot(PrevisRoot);
'''


def previs_root_tsx(plan, n, parts, project_root=pathlib.Path(".")):
    """Generate the complete isolated root for exactly one selected plan."""
    project_root = pathlib.Path(project_root)
    source_dir = project_root / "src"
    built = [(component, duration) for _, component, duration, _transition in parts
             if (source_dir / "scenes" / f"{component}.jsx").is_file()]
    master_path = source_dir / f"V{n}Master.jsx"
    has_master = master_path.is_file()
    fps = int(plan.get("fps", 30))
    width = int(plan.get("width", 1080))
    height = int(plan.get("height", 1920))
    header = (f"/** {AUTOGEN}. Source: input/scene_plan{n}.json.\n"
              " * Isolated previs registration; production roots are intentionally not imported.\n"
              " */\n")
    if not built and not has_master:
        return header + "export const PrevisRoot = () => null;\n"

    remotion_names = "Composition, Folder" if built else "Composition"
    imports = [f'import {{ {remotion_names} }} from "remotion";']
    imports.extend(f'import {{ {component}, {duration} }} from "./scenes/{component}";'
                   for component, duration in built)
    if has_master:
        imports.append(f'import {{ V{n}Master, MASTER{n}_DURATION }} from "./V{n}Master";')

    body = []
    if built:
        body.append(f'      <Folder name="V{n}-Scenes">')
        body.extend(
            f'        <Composition id="{component}" component={{{component}}} '
            f'durationInFrames={{{duration}}} fps={{{fps}}} width={{{width}}} height={{{height}}} />'
            for component, duration in built)
        body.append("      </Folder>")
    if has_master:
        body.append(
            f'      <Composition id="V{n}Master" component={{V{n}Master}} '
            f'durationInFrames={{MASTER{n}_DURATION}} fps={{{fps}}} '
            f'width={{{width}}} height={{{height}}} />')
    return (header + "\n".join(imports) + "\n\n"
            "export const PrevisRoot = () => (\n"
            "  <>\n" + "\n".join(body) + "\n  </>\n);\n")


def step_register(plan, n, parts, check, force=False, project_root=None):
    """Own PrevisRoot/index deterministically without reading the production root."""
    project_root = pathlib.Path(project_root or pathlib.Path.cwd()).resolve()
    paths = state.video_paths(project_root, f"V{n}")
    root_path, index_path = paths["previs_root"], paths["entry"]
    expected_root = previs_root_tsx(plan, n, parts, project_root)
    current_root = root_path.read_text(encoding="utf-8") if root_path.is_file() else None
    current_index = index_path.read_text(encoding="utf-8") if index_path.is_file() else None
    if current_root == expected_root and current_index == INDEX_TS:
        print("register: PrevisRoot.tsx và index.ts đã đúng, không có gì để thêm.")
        return True
    if check:
        changed = []
        if current_root != expected_root:
            changed.append("src/PrevisRoot.tsx")
        if current_index != INDEX_TS:
            changed.append("src/index.ts")
        print(f"register: {', '.join(changed)} LỆCH hợp đồng previs cô lập - chạy assemble.")
        return False
    if current_root is not None and AUTOGEN not in current_root and not force:
        print("register: src/PrevisRoot.tsx không mang dấu AUTO-GENERATED; "
              "không đè (dùng --force nếu chắc chắn).")
        return False
    root_path.parent.mkdir(parents=True, exist_ok=True)
    root_path.write_text(expected_root, encoding="utf-8")
    index_path.write_text(INDEX_TS, encoding="utf-8")
    print(f"register: đã ghi {root_path} và chuẩn hoá {index_path} cho V{n}.")
    return True


# -------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("plan", type=pathlib.Path)
    ap.add_argument("--only", choices=["captions", "master", "register"])
    ap.add_argument("--check", action="store_true",
                    help="chỉ so với bản sinh lại, không ghi; thoát 1 nếu lệch")
    ap.add_argument("--force", action="store_true",
                    help="cho phép đè file không mang dấu AUTO-GENERATED")
    args = ap.parse_args()

    if not args.plan.exists():
        die(f"không thấy {args.plan}")
    plan, n, m, words_path = load_plan(args.plan)
    parts = scene_parts(plan, n)

    ok = True
    if args.only in (None, "captions"):
        ok = step_captions(plan, n, m, words_path, args.check, args.force) and ok
    if args.only in (None, "master"):
        ok = step_master(plan, n, m, parts, args.check, args.force) and ok
    if args.only in (None, "register"):
        project_root = state.project_root(args.plan)
        ok = step_register(plan, n, parts, args.check, args.force, project_root) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
