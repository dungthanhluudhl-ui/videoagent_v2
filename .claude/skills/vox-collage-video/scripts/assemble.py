"""
assemble.py - sinh phần CƠ KHÍ của một video từ scene_plan<N>.json.

Ba thứ trước nay viết tay mỗi video, dù 100% suy ra được từ plan + words file:

  1. src/captionData<M>.js   - phụ đề bám từ (4 từ/dòng, reset theo segment,
                               frame = round(t*fps)). M lấy từ "wordsFile".
  2. src/V<N>Master.jsx      - master timeline. Phép đệm rail của
                               TransitionSeries (SKILL.md bước 7) là nguồn lỗi
                               đã ghi nhận: đệm thiếu rail ĐẦU kéo mọi cảnh từ
                               S2 trở đi sớm nửa giây so với audio của chính nó.
  3. src/PrevisRoot.tsx      - root composition cô lập, sở hữu hoàn toàn bởi script.
     src/index.ts            - chỉ đăng ký PrevisRoot, không import root production.

Chạy từ GỐC dự án. Mặc định chạy cả ba bước, mỗi bước tự biết "chưa tới lúc":

    py -3 .claude/skills/vox-collage-video/scripts/assemble.py input/scene_plan13.json
    py -3 ... assemble.py input/scene_plan13.json --only captions
    py -3 ... assemble.py input/scene_plan13.json --check     # chỉ so, không ghi

- captions: ghi captionData<M>.js (+ shared<M>.jsx nếu chưa có). File viết tay
  có sẵn (V3-V11) được giữ nguyên - chỉ so nội dung, không đè.
- master:   chỉ sinh khi MỌI file cảnh trong plan đã tồn tại; thiếu cảnh nào
  thì liệt kê rồi bỏ qua (chưa tới lúc KHÁC có lỗi - bài học của cutout_gate).
- register: sinh lại toàn bộ PrevisRoot.tsx từ đúng plan đang chọn và chuẩn hoá
  index.ts. Không đọc, import hay sửa src/Root.jsx.

Transition: mặc định cắt thẳng. Chỉ khai "transitionIn": "fade" khi quan hệ
giữa hai cảnh thật sự cần giữ cảm giác liên tục; "none" vẫn được chấp nhận như
tên cũ của cắt thẳng.
Muốn thứ gì cầu kỳ hơn thì viết master bằng tay - và file tay KHÔNG BAO GIỜ
bị script này đè: mọi file sinh ra đều mang dấu AUTO-GENERATED, gặp file
không có dấu là dừng (trừ khi --force).

--check thoát 1 khi file trên đĩa lệch với bản sinh lại từ plan - dùng để
phát hiện master/captions bị sửa tay lệch khỏi hợp đồng.
"""

import argparse
import json
import pathlib
import re
import sys

import stage_state as state

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except AttributeError:
    pass

AUTOGEN = "AUTO-GENERATED by assemble.py"
T_FADE = 15          # khung; khớp mọi master đã ship
WORDS_PER_LINE = 4   # khớp captionData3..11 đã ship
CANVAS_BG = "#E7E3D9"


def die(msg):
    print(f"assemble: {msg}")
    sys.exit(1)


def load_plan(path):
    plan = json.loads(path.read_text(encoding="utf-8"))
    video = plan.get("video", "")
    m = re.fullmatch(r"V(\w+)", video)
    if not m:
        die(f'plan thiếu "video": "V<N>" (đang là {video!r})')
    n = m.group(1)
    words_file = plan.get("wordsFile", "")
    wm = re.search(r"words(\w+?)_aligned\.json$", words_file)
    if not wm:
        die(f'plan thiếu "wordsFile" dạng input/words<M>_aligned.json (đang là {words_file!r})')
    return plan, n, wm.group(1), pathlib.Path(words_file)


def scene_parts(plan, n):
    """[(id, component, duration_const, transition_in)] theo thứ tự plan."""
    out = []
    for s in plan["scenes"]:
        num = s["id"].lstrip("S")
        tin = s.get("transitionIn", "none")
        if tin not in ("fade", "none"):
            die(f'{s["id"]}: transitionIn={tin!r} - chỉ hỗ trợ "fade"/"none"; '
                "kiểu khác thì viết master bằng tay")
        out.append((s["id"], f"V{n}Scene{num}", f"V{n}SCENE{num.upper()}_DURATION", tin))
    return out


# ---------------------------------------------------------------- captions

def build_caption_lines(words_path, fps):
    words = json.loads(words_path.read_text(encoding="utf-8"))["words"]
    lines, cur, cur_seg = [], [], None
    for text, start, end, seg in words:
        if seg != cur_seg or len(cur) >= WORDS_PER_LINE:
            if cur:
                lines.append(cur)
            cur, cur_seg = [], seg
        cur.append({"text": text,
                    "startFrame": round(start * fps),
                    "endFrame": round(end * fps)})
    if cur:
        lines.append(cur)
    return lines


def caption_js(m, lines):
    return (f"// {AUTOGEN} - sinh lại từ plan, đừng sửa tay.\n"
            f"export const CAPTION_LINES{m} = "
            + json.dumps(lines, ensure_ascii=False, indent=2) + ";\n")


def parse_caption_js(text):
    s = text[text.index("export const"):].split("=", 1)[1].strip().rstrip(";").rstrip()
    return json.loads(s)


